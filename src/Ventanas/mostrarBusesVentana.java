    private void buscarBusesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarBusesActionPerformed
         String texto = buscarBuses.getText().trim();

        if (texto.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un ID para buscar.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        DefaultTableModel modeloTabla =
                (DefaultTableModel) tablaBuses.getModel();

        try {
            int id = Integer.parseInt(texto);

            Buses bus = gestion.buscarBus(id);

            modeloTabla.setRowCount(0);

            modeloTabla.addRow(new Object[]{
                bus.getIdBus(),
                bus.getCantidadPasajeros() + "/" + bus.getCapacity(),
                bus.getDisponibility()
            });

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "El ID debe ser un número.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE

            );

        } catch (ElementoNoEncontradoException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_buscarBusesActionPerformed

  

