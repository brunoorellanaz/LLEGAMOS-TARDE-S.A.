    private void buscarPasajerosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarPasajerosActionPerformed
          String texto = buscarPasajeros.getText().trim();

        if (texto.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un ID para buscar.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        DefaultTableModel modeloTabla =
                (DefaultTableModel) jTable1.getModel();

        try {
            int id = Integer.parseInt(texto);

            Pasajeros pasajero = gestion.buscarPasajero(id);

            modeloTabla.setRowCount(0);

            modeloTabla.addRow(new Object[]{
                pasajero.getIdPasajero(),
                pasajero.getNombre(),
                pasajero.getEdad(),
                pasajero.getBus(),
                pasajero.getTipo()
            });

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "El ID debe ser un número.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (ElementoNoEncontradoException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_buscarPasajerosActionPerformed

