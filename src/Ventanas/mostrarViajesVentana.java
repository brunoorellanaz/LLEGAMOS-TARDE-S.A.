    private void buscarViajesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarViajesActionPerformed
       String texto = buscarViajes.getText().trim();

        if (texto.isEmpty()) {
            JOptionPane.showMessageDialog(
            this,
            "Ingrese un ID para buscar.",
            "Error",
            JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        DefaultTableModel modeloTabla =
                (DefaultTableModel) jTable1.getModel();

        try {
            int id = Integer.parseInt(texto);

            Viajes viaje = gestion.buscarViaje(id);

            modeloTabla.setRowCount(0);

            modeloTabla.addRow(new Object[]{
                viaje.getIdViaje(),
                viaje.getOrigen(),
                viaje.getDestino(),
                viaje.getCostoViaje(),
                viaje.getCostoPasaje(),
                viaje.getCantidadBuses(),
                viaje.getFechaHoraInicio()
            });

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "El ID debe ser un número.",
                "Error",
                JOptionPane.ERROR_MESSAGE
            );

        } catch (ElementoNoEncontradoException e) {

            JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_buscarViajesActionPerformed

